"""Small cache boundary consumed by retrieval; no transport or storage types."""

from typing import Any, Protocol


class RetrievalCache(Protocol):
    def get(self, bucket: str, key: str) -> Any: ...
    def put(self, bucket: str, key: str, value: Any) -> None: ...
    def semantic(self, scope: str, vector: list[float] | None, tokens: list[str]) -> set[str] | None: ...
    def remember_pool(
        self, scope: str, query: str, vector: list[float] | None, tokens: list[str], ids: list[str]
    ) -> None: ...
