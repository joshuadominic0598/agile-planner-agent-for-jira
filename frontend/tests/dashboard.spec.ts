import { test, expect, type Page } from '@playwright/test';

function exportCSV() {
  const headers = ['Issue key', 'Summary', 'Issue Type', 'Status', 'Status Category', 'Project key', 'Project name', 'Priority', 'Assignee', 'Sprint', 'Sprint', 'Comment', 'Comment', 'Description'];
  const rows = Array.from({ length: 25 }, (_, i) => [`DEMO-${i + 1}`, `Improve the project ${i + 1}`, i % 3 === 0 ? 'Bug' : 'Story', i % 4 === 0 ? 'Production' : i % 2 ? 'Testing' : 'Done', i % 2 && i % 4 !== 0 ? 'In Progress' : 'Done', 'DEMO', 'Demo project', i % 3 === 0 ? 'High' : 'Medium', i % 2 ? 'Alex Chen' : 'Sam Rivera', 'Sprint 10', 'Sprint 9', 'First note', 'Second note', '<script>alert(1)</script>']);
  rows.push(['DEMO-26', 'Unscheduled issue', 'Task', 'To Do', 'To Do', 'DEMO', 'Demo project', 'Low', '', '', '', '', '', '']);
  rows.push(['OTHER-1', 'Other project issue', 'Task', 'Done', 'Done', 'OTHER', 'Another project', 'Low', '', '', '', '', '', '']);
  return [headers, ...rows].map(row => row.map(v => `"${v.replaceAll('"', '""')}"`).join(',')).join('\r\n');
}

async function upload(page: Page) {
  await page.goto('/');
  await page.getByLabel('Jira CSV file').setInputFiles({ name: 'demo.csv', mimeType: 'text/csv', buffer: Buffer.from(exportCSV()) });
  await page.getByRole('button', { name: 'Explore my project' }).click();
  await expect(page.getByRole('heading', { name: 'Choose how your statuses appear.' })).toBeVisible();
  await page.getByRole('button', { name: 'Use original statuses', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Your project, in focus.' })).toBeVisible();
  await page.getByLabel('Project', { exact: true }).selectOption('DEMO');
  await page.getByRole('link', { name: 'Sprint explorer', exact: true }).click();
  await expect(page.getByLabel('Sprint', { exact: true })).toHaveValue('Sprint 10');
  await expect(page.getByRole('button', { name: 'DEMO-25', exact: true })).toBeVisible();
}

